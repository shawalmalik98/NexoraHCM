function deactivate_confirm(company_id) {
    $('#modal-danger').modal('show');
    $('#delete_company_id').val(company_id)
}

$('#delete_departform').submit(function (e) {

    $('#delete-btn').prop('disabled', true);
    $('#delete-btn').attr('data-kt-indicator', 'on');
    $('#delete-btn').css('cursor', 'not-allowed');
    var company_id = $('#delete_company_id').val()
    e.preventDefault();
    $.ajax({
        url: base_url + '/companies/discard-company/' + company_id,
        type: 'GET',
        success: function (data) {
            if (data.status == 'TRUE') {
                Toast.fire({
                    icon: 'success',
                    title: data.msg,
                    timer: 3000,
                })
                setTimeout(() => {
                    location.reload();
                }, 3000);
            } else {
                Toast.fire({
                    icon: 'warning',
                    title: data.msg,
                    timer: 8000,
                })
                $('#delete-btn').prop('disabled', false);
                $('#delete-btn').removeAttr('data-kt-indicator');
                $('#delete-btn').css('cursor', 'pointer');
            }
        },
        error: function (jqXHR, textStatus) {
            var errorStatus = jqXHR.status;
            $('#delete-btn').prop('disabled', false);
            $('#delete-btn').removeAttr('data-kt-indicator');
            $('#delete-btn').css('cursor', 'pointer');
            if (errorStatus == 0) {
                Toast.fire({
                    icon: 'warning',
                    title: 'Internet Connection Problem',
                    timer: 3000,
                })
            } else {
                if (errorStatus == 419) {
                    location.reload();
                } else {
                    Toast.fire({
                        icon: 'warning',
                        title: 'Try Again. Error Code ' + errorStatus,
                        timer: 3000,
                    })
                }
            }
        }
    });
});

